#!/usr/bin/env node
/* Builds Islamic-Finance-Learning.html: the whole app in ONE self-contained file.
   Inlines styles.css, the icon, every module and view, and ALL content data (18 chapters,
   glossary, concepts, diagrams, comparisons, cases, mode finder, study plans), so it can be
   double-clicked, emailed or copied anywhere and works with no other files and no internet.
   Source files are not changed; re-run after any edit:  node tools/build-standalone.cjs */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const OUT = 'Islamic-Finance-Learning.html';

let html = read('index.html');
const scripts = [...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map((m) => m[1]);
if (!scripts.length) throw new Error('No scripts found in index.html');

// All lazily-loaded content, registered up front (the loader then resolves instantly).
const data = ['data/glossary.js', 'data/concepts.js', 'data/diagrams.js', 'data/comparisons.js', 'data/case-studies.js', 'data/mode-finder.js', 'data/study-plans.js'];
for (let n = 1; n <= 18; n++) data.push('data/chapters/ch' + String(n).padStart(2, '0') + '.js');

// Make script text safe inside an inline <script> element.
const safe = (js) => js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
const block = (name, js) => '<script data-src="' + name + '">\n' + safe(js) + '\n</script>';

const order = [];
scripts.forEach((s) => { order.push(s); if (s === 'data/registry.js') order.push(...data); });
const inlined = [block('standalone-flag', 'window.IFL_STANDALONE = true;')].concat(order.map((s) => block(s, read(s)))).join('\n');

// Replace the <script src> run with inline scripts (function replacer: no $-pattern surprises).
const first = html.indexOf('<script src="'), lastTag = '<script src="' + scripts[scripts.length - 1] + '"></script>';
const last = html.indexOf(lastTag) + lastTag.length;
html = html.slice(0, first) + inlined + html.slice(last);

// Stylesheet, icons, manifest.
html = html.replace('<link rel="stylesheet" href="styles.css">', () => '<style>\n' + read('styles.css') + '\n</style>');
const iconUri = 'data:image/svg+xml;base64,' + Buffer.from(read('assets/icons/icon.svg')).toString('base64');
html = html.replace(/assets\/icons\/icon\.svg/g, iconUri);
const png = fs.readFileSync(path.join(root, 'assets/icons/icon-192.png')).toString('base64');
html = html.replace('assets/icons/icon-192.png', 'data:image/png;base64,' + png);
html = html.replace(/\s*<link rel="manifest" href="manifest.json">/, '');
html = html.replace('<!-- Data registry and lightweight course index (full chapter content is lazy-loaded). -->', '<!-- Standalone build: all content and code are inlined below. Generated by tools/build-standalone.cjs — edit the source files, not this one. -->');

const leftovers = html.match(/\s(src|href)="(?!#|data:|https?:|mailto:)[^"]+\.(js|css|json|svg|png)"/g);
if (leftovers) throw new Error('External references remain: ' + leftovers.join(', '));
fs.writeFileSync(path.join(root, OUT), html);
console.log(OUT + ' written: ' + (html.length / 1024 / 1024).toFixed(2) + ' MB, ' + order.length + ' scripts inlined');
