#!/usr/bin/env node
/* Builds a single, self-contained HTML file with every stylesheet, data
 * file and module inlined — no external requests, so it runs by double-
 * clicking it and opening in a browser (file:// protocol), fully offline,
 * with 100% of the modular app's content and functionality preserved.
 *
 * The modular source (index.html + styles.css + data/*.js + modules/*.js)
 * remains the source of truth for development; run this script again
 * after any change to regenerate the standalone build:
 *
 *   node tools/build-standalone.js
 */
"use strict";
var fs = require("fs");
var path = require("path");

var ROOT = path.join(__dirname, "..");
var OUT_FILE = path.join(ROOT, "Understanding-Islamic-Finance-STANDALONE.html");

function read(rel) { return fs.readFileSync(path.join(ROOT, rel), "utf8"); }

// Escape any literal "</script" so an inlined file can never prematurely
// close the surrounding <script> tag (defense in depth; source files
// shouldn't contain this string, but bundlers should never trust that).
function safeInline(js) {
  return js.replace(/<\/script/gi, "<\\/script");
}

function main() {
  var html = read("index.html");

  // 1. Extract every <script src="..."></script> reference, in document order.
  var scriptSrcRe = /<script src="([^"]+)"><\/script>/g;
  var scriptSrcs = [];
  var m;
  while ((m = scriptSrcRe.exec(html))) scriptSrcs.push(m[1]);
  if (!scriptSrcs.length) throw new Error("No <script src> tags found in index.html — is the file structure unchanged?");

  // 2. Inline styles.css into a <style> tag, replacing the <link rel="stylesheet">.
  var css = read("styles.css");
  html = html.replace(
    /<link rel="stylesheet" href="styles\.css">/,
    function () { return "<style>\n" + css + "\n</style>"; }
  );

  // 3. Inline manifest.json as a data: URI so the <link rel="manifest"> never
  //    404s under file:// (PWA install itself still requires https, which a
  //    local double-clicked file can't provide — that one and only PWA
  //    capability is inherently unavailable offline-by-file, same as it
  //    would be in any browser; everything else in the app is unaffected).
  var manifestJson = read("manifest.json");
  var manifestDataUri = "data:application/manifest+json;base64," + Buffer.from(manifestJson, "utf8").toString("base64");
  html = html.replace(/<link rel="manifest" href="manifest\.json">/, function () { return '<link rel="manifest" href="' + manifestDataUri + '">'; });

  // 4. Replace each <script src="..."></script> with its inlined content,
  //    in the same order, preserving execution order exactly. Uses a
  //    replacer FUNCTION (not a string) — some source files legitimately
  //    contain "$&"/"$`"/"$'" (e.g. router.js's regex-escaping helper),
  //    which String.replace treats as special patterns when the
  //    replacement is a plain string, corrupting the output.
  scriptSrcs.forEach(function (src) {
    var code = safeInline(read(src));
    var tag = '<script src="' + src + '"></script>';
    html = html.replace(tag, function () { return "<script>\n" + code + "\n</script>"; });
  });

  // 5. Sanity: no external file references should remain.
  var leftoverSrc = html.match(/<script src="/g);
  var leftoverLink = html.match(/<link rel="stylesheet" href="/g);
  if (leftoverSrc || leftoverLink) {
    throw new Error("Bundle still references external files — inlining incomplete.");
  }

  // 6. A small marker + note in the <head> so it's clear this is the
  //    generated standalone build, not the source of truth.
  html = html.replace(
    "<title>Understanding Islamic Finance · Learning Platform</title>",
    "<title>Understanding Islamic Finance · Learning Platform</title>\n" +
    "<!-- STANDALONE BUILD: generated by tools/build-standalone.js from the modular\n" +
    "     source (index.html, styles.css, data/*.js, modules/*.js). Edit the\n" +
    "     modular source and re-run that script rather than editing this file. -->"
  );

  fs.writeFileSync(OUT_FILE, html, "utf8");
  var sizeMb = (Buffer.byteLength(html, "utf8") / (1024 * 1024)).toFixed(2);
  console.log("Wrote " + path.relative(ROOT, OUT_FILE) + " (" + sizeMb + " MB), inlining " + scriptSrcs.length + " scripts + styles.css + manifest.json.");
}

main();
