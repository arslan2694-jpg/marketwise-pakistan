/* Assembles the single self-contained deliverable from the modular working files:
   index.html + styles.css + data/*.js + modules (all views) + app.js  →  one .html file.
   Usage: node tools/build-standalone.js [output path] */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
/* --lab builds the small companion app (diagrams, games, numericals, calculators) from lite/index.html */
const LAB = process.argv.includes('--lab');
const argOut = process.argv.slice(2).filter(a => !a.startsWith('--'))[0];
const OUT = argOut || path.join(ROOT, '..', LAB ? 'Islamic-Finance-Practice-Lab.html' : 'Understanding-Islamic-Finance-MBA-Learning-System.html');
let html = fs.readFileSync(path.join(ROOT, LAB ? 'lite/index.html' : 'index.html'), 'utf8');
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) => '<style>\n' + fs.readFileSync(path.join(ROOT, href), 'utf8') + '\n</style>');
let n = 0;
html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
  const body = fs.readFileSync(path.join(ROOT, src), 'utf8').replace(/<\/script/gi, '<\\/script');
  n++;
  return '<script data-src="' + src + '">\n' + body + '\n</script>';
});
html = html.replace('<body>', '<body>\n<!-- Single-file build generated by merged-src/tools/build-standalone.js from the modular sources (' + (LAB ? 'lite/, ' : '') + 'index.html, styles.css, data/, modules/, app.js). Edit those and rebuild; do not edit this file. -->');
fs.writeFileSync(OUT, html);
console.log('wrote', OUT, (html.length / 1048576).toFixed(2) + ' MB,', n, 'scripts inlined');
